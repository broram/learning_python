# latihan kita yang pertama tentang operator aritmatika
a = 11
b = 3

# menggunakan operator penjumlahan 
hasil = a + b
print(a, '+', b, '=', hasil)

# menggunakan operator pengurangan 
hasil = a - b 
print(a, '-', b, '=', hasil)

# menggunakan operator perkalian
hasil = b * a
print(a, '*', b, '=', hasil)

# menggunakan operator pembagian
hasil = a / b
print(a, '/', b, '=', hasil)

# menggunakan operator sisa bagi (modulus)
hasil = a % b 
print(a, '%', b, '=', hasil)

# menggunakan operator pemangkatan
hasil = a ** b
print(a, '**', b, '=', hasil)

# menggunakan operator floor division
hasil = a // b 
print(a, '//', b, '=', hasil) 

