'''latihan operator perbandingan (comparison python)'''

x = 4
y = 3

#equal
hasil = (x == y)
print('hasil dari', x ,'==', y, hasil)

# not equal
hasil = (x != y)
print('hasil dari', x, '!=', y, hasil)

# greater than
hasil = (x > y)
print('hasil dari', x, '>', y, hasil)

# less than
hasil = (x < y)
print('hasil dari', x, '<', y, hasil)

