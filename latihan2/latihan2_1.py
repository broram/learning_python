''' buatlah program python yang meminta dua angka dari penggunaan,
lalu tampilkan hasil dari operator berikut'''

# input dua angka dari user
a = float(input("Masukan angka pertama: "))
b = float(input("Masukan angka kedua: "))

print(f"penjumlahan: {a} + {b} = {a + b}")
print(f"pengurangan: {a} - {b} = {a - b}")
print(f"perkalian  : {a} * {b} = {a * b}")
print(f"pembagian  : {a} / {b} = {a / b}")
print(f"modulus    : {a} & {b} = {a & b}")